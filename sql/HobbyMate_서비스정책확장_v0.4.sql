UPDATE HM_REPORT SET REPORT_REASON = 'SEXUAL_CONTENT' WHERE REPORT_REASON = 'INAPPROPRIATE';
UPDATE HM_REPORT SET REPORT_REASON = 'FRAUD_FALSE_INFORMATION' WHERE REPORT_REASON = 'FRAUD';
UPDATE HM_REPORT SET REPORT_REASON = 'OTHER' WHERE REPORT_REASON = 'PRIVACY';
UPDATE HM_REPORT SET REPORT_STATUS = 'COMPLETED' WHERE REPORT_STATUS = 'RESOLVED';

ALTER TABLE HM_REPORT
    MODIFY REPORT_CONTENT VARCHAR(500) NULL COMMENT '신고 상세 사유, OTHER일 때 필수(최대 500자)',
    ADD COLUMN FALSE_REPORT_YN CHAR(1) NOT NULL DEFAULT 'N' COMMENT '허위·악의적 신고 판정 여부' AFTER PROCESS_RESULT,
    ADD COLUMN ADMIN_MEMO VARCHAR(2000) NULL COMMENT '관리자 내부 메모' AFTER FALSE_REPORT_YN,
    ADD UNIQUE KEY UK_HM_REPORT_DUPLICATE (REPORTER_MEMBER_ID, TARGET_TYPE, TARGET_ID),
