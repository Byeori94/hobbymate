-- 8. 모임 회원 이력·영구 가입 제한·즐겨찾기
CREATE TABLE IF NOT EXISTS HM_CLUB_MEMBER_HISTORY (
    CLUB_MEMBER_HISTORY_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '모임 회원 이력 PK',
    CLUB_ID BIGINT UNSIGNED NOT NULL COMMENT '모임 FK',
    MEMBER_ID BIGINT UNSIGNED NOT NULL COMMENT '대상 회원 FK',
    EVENT_TYPE VARCHAR(30) NOT NULL COMMENT 'JOIN, LEFT, KICKED, ROLE_CHANGED, LEADER_TRANSFER, CLUB_CLOSED',
    BEFORE_ROLE VARCHAR(20) NULL COMMENT '변경 전 역할',
    AFTER_ROLE VARCHAR(20) NULL COMMENT '변경 후 역할',
    BEFORE_STATUS VARCHAR(20) NULL COMMENT '변경 전 상태',
    AFTER_STATUS VARCHAR(20) NULL COMMENT '변경 후 상태',
    EVENT_REASON VARCHAR(2000) NULL COMMENT '처리 사유',
    ACTION_BY BIGINT UNSIGNED NULL COMMENT '처리 회원 FK',
    REJOIN_AVAILABLE_AT DATETIME NULL COMMENT '12시간 재가입 제한 종료 일시',
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '처리 일시',
    PRIMARY KEY (CLUB_MEMBER_HISTORY_ID),
    KEY IX_HM_CLUB_MEMBER_HISTORY_MEMBER (CLUB_ID, MEMBER_ID, CREATED_AT),
    KEY IX_HM_CLUB_MEMBER_HISTORY_ACTION_BY (ACTION_BY),
    CONSTRAINT FK_HM_CLUB_MEMBER_HISTORY_CLUB FOREIGN KEY (CLUB_ID) REFERENCES HM_CLUB (CLUB_ID),
    CONSTRAINT FK_HM_CLUB_MEMBER_HISTORY_MEMBER FOREIGN KEY (MEMBER_ID) REFERENCES HM_MEMBER (MEMBER_ID),
    CONSTRAINT FK_HM_CLUB_MEMBER_HISTORY_ACTION FOREIGN KEY (ACTION_BY) REFERENCES HM_MEMBER (MEMBER_ID),
    CONSTRAINT CK_HM_CLUB_MEMBER_HISTORY_EVENT CHECK (EVENT_TYPE IN ('JOIN','LEFT','KICKED','ROLE_CHANGED','LEADER_TRANSFER','CLUB_CLOSED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='모임 가입·탈퇴·강퇴·역할 변경 이력';

