-- HobbyMate 서비스 정책 확장 v0.4
-- 대상: v0.1~v0.3이 적용된 기존 MariaDB
-- 목적: 모임·만남·게시판·알림·신고·관리자·개인정보 확정 정책 반영
-- 주의: 운영 데이터가 존재하므로 DROP TABLE 및 데이터 초기화를 수행하지 않는다.

SET NAMES utf8mb4;

-- 1. 회원 권한·상태·탈퇴 후 개인정보 정리 구조
ALTER TABLE HM_MEMBER
    DROP CONSTRAINT CK_HM_MEMBER_ROLE,
    DROP CONSTRAINT CK_HM_MEMBER_STATUS,
    MODIFY NAME VARCHAR(50) NULL COMMENT '본인인증 이름, 탈퇴 30일 후 익명화 가능',
    MODIFY PHONE VARCHAR(30) NULL COMMENT '휴대폰 번호, 탈퇴 30일 후 익명화 가능',
    MODIFY BIRTH_DATE DATE NULL COMMENT '생년월일, 탈퇴 30일 후 익명화 가능',
    MODIFY GENDER VARCHAR(10) NULL COMMENT '성별, 탈퇴 30일 후 익명화 가능',
    ADD COLUMN PROFILE_THUMBNAIL_URL VARCHAR(1000) NULL COMMENT '200x200 프로필 썸네일 저장 키' AFTER PROFILE_IMAGE_URL,
    ADD COLUMN PERSONAL_INFO_PURGED_AT DATETIME NULL COMMENT '탈퇴 후 개인정보 삭제·익명화 일시' AFTER WITHDRAWN_AT,
    ADD KEY IX_HM_MEMBER_STATUS_CREATED (MEMBER_STATUS, CREATED_AT),
    ADD CONSTRAINT CK_HM_MEMBER_ROLE CHECK (MEMBER_ROLE IN ('USER','ADMIN','SUPER_ADMIN')),
    ADD CONSTRAINT CK_HM_MEMBER_STATUS CHECK (MEMBER_STATUS IN ('ACTIVE','SUSPENDED','PERMANENT_BANNED','WITHDRAWN')),
    ADD CONSTRAINT CK_HM_MEMBER_GENDER_V04 CHECK (GENDER IS NULL OR GENDER IN ('FEMALE','MALE'));

-- 기존 성별 CHECK는 NOT NULL 전제를 제거하기 위해 교체한다.
ALTER TABLE HM_MEMBER DROP CONSTRAINT CK_HM_MEMBER_GENDER;

-- 2. 모임 폐쇄 구분·복구·최근 활동
ALTER TABLE HM_CLUB
    ADD COLUMN JOIN_GUIDE VARCHAR(1000) NULL COMMENT '승인제 가입 신청 안내·질문, 화면 입력 최대 500자' AFTER JOIN_TYPE,
    ADD COLUMN CLOSED_TYPE VARCHAR(20) NULL COMMENT '폐쇄 유형: LEADER 자진폐쇄, ADMIN 관리자폐쇄' AFTER RECRUIT_STATUS,
    ADD COLUMN CLOSED_BY BIGINT UNSIGNED NULL COMMENT '폐쇄 처리 회원 FK' AFTER CLOSED_TYPE,
    ADD COLUMN CLOSED_REASON VARCHAR(2000) NULL COMMENT '폐쇄 사유' AFTER CLOSED_BY,
    ADD COLUMN RECOVERABLE_UNTIL DATETIME NULL COMMENT '복구 가능 기한' AFTER CLOSED_AT,
    ADD COLUMN LAST_ACTIVITY_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '최근 활동 일시' AFTER UPDATED_AT,
    ADD KEY IX_HM_CLUB_RECENT_ACTIVITY (CLUB_STATUS, LAST_ACTIVITY_AT),
    ADD KEY IX_HM_CLUB_CREATED (CREATED_AT),
    ADD KEY IX_HM_CLUB_CLOSED_BY (CLOSED_BY),
    ADD CONSTRAINT FK_HM_CLUB_CLOSED_BY FOREIGN KEY (CLOSED_BY) REFERENCES HM_MEMBER (MEMBER_ID),
    ADD CONSTRAINT CK_HM_CLUB_CLOSED_TYPE CHECK (CLOSED_TYPE IS NULL OR CLOSED_TYPE IN ('LEADER','ADMIN'));

-- 3. 모임 회원 상태와 승인 대기 중복 방지
ALTER TABLE HM_CLUB_MEMBER
    DROP CONSTRAINT CK_HM_CLUB_MEMBER_STATUS;

UPDATE HM_CLUB_MEMBER
SET MEMBER_STATUS = 'LEFT'
WHERE MEMBER_STATUS = 'WITHDRAWN';

ALTER TABLE HM_CLUB_MEMBER
    ADD CONSTRAINT CK_HM_CLUB_MEMBER_STATUS CHECK (MEMBER_STATUS IN ('ACTIVE','LEFT','KICKED'));

ALTER TABLE HM_CLUB_JOIN_REQUEST
    ADD COLUMN WAITING_MEMBER_ID BIGINT UNSIGNED
        AS (CASE WHEN REQUEST_STATUS = 'WAITING' THEN MEMBER_ID ELSE NULL END) PERSISTENT
        COMMENT '승인 대기 중복 방지용 생성 컬럼',
    ADD UNIQUE KEY UK_HM_CLUB_JOIN_WAITING (CLUB_ID, WAITING_MEMBER_ID);

-- 4. 만남 선착순·대기 제안·취소·출석/노쇼
ALTER TABLE HM_MEETING
    DROP CONSTRAINT CK_HM_MEETING_MAX_MEMBER_COUNT,
    ADD COLUMN PARTICIPATION_METHOD VARCHAR(20) NOT NULL DEFAULT 'FIRST_COME' COMMENT '참가 방식: FIRST_COME 선착순' AFTER MEETING_TYPE,
    ADD COLUMN CANCELED_BY BIGINT UNSIGNED NULL COMMENT '취소 처리 회원 FK' AFTER CANCELED_AT,
    ADD COLUMN CANCEL_TYPE VARCHAR(20) NULL COMMENT '취소 주체: CREATOR, LEADER, MANAGER, ADMIN, CLUB_CLOSED' AFTER CANCELED_BY,
    ADD COLUMN CANCEL_REASON VARCHAR(2000) NULL COMMENT '취소 사유' AFTER CANCEL_TYPE,
    ADD KEY IX_HM_MEETING_CANCELED_BY (CANCELED_BY),
    ADD KEY IX_HM_MEETING_CREATED (CREATED_AT),
    ADD CONSTRAINT FK_HM_MEETING_CANCELED_BY FOREIGN KEY (CANCELED_BY) REFERENCES HM_MEMBER (MEMBER_ID),
    ADD CONSTRAINT CK_HM_MEETING_PARTICIPATION_METHOD CHECK (PARTICIPATION_METHOD = 'FIRST_COME'),
    ADD CONSTRAINT CK_HM_MEETING_CANCEL_TYPE CHECK (CANCEL_TYPE IS NULL OR CANCEL_TYPE IN ('CREATOR','LEADER','MANAGER','ADMIN','CLUB_CLOSED')),
    ADD CONSTRAINT CK_HM_MEETING_MAX_MEMBER_COUNT CHECK (MAX_MEMBER_COUNT >= 2);

UPDATE HM_MEETING_PARTICIPANT
SET PARTICIPATION_STATUS = 'CONFIRMED',
    CONFIRMED_AT = COALESCE(CONFIRMED_AT, APPLIED_AT)
WHERE PARTICIPATION_STATUS = 'APPLIED';

ALTER TABLE HM_MEETING_PARTICIPANT
    DROP CONSTRAINT CK_HM_MEETING_PARTICIPANT_STATUS,
    ADD COLUMN WAITING_ORDER INT UNSIGNED NULL COMMENT '대기 순번' AFTER PARTICIPATION_STATUS,
    ADD COLUMN WAITING_REGISTERED_AT DATETIME NULL COMMENT '대기 등록 일시' AFTER WAITING_ORDER,
    ADD COLUMN OFFERED_AT DATETIME NULL COMMENT '참가 제안 일시' AFTER WAITING_REGISTERED_AT,
    ADD COLUMN OFFER_EXPIRES_AT DATETIME NULL COMMENT '참가 제안 만료 일시' AFTER OFFERED_AT,
    ADD COLUMN OFFER_RESPONDED_AT DATETIME NULL COMMENT '참가 제안 응답 일시' AFTER OFFER_EXPIRES_AT,
    ADD COLUMN OFFER_RESPONSE VARCHAR(20) NULL COMMENT '제안 응답: ACCEPTED, DECLINED, EXPIRED' AFTER OFFER_RESPONDED_AT,
    ADD COLUMN ATTENDED_YN CHAR(1) NULL COMMENT '실제 참석 여부' AFTER ATTENDANCE_PROCESSED_AT,
    ADD COLUMN NO_SHOW_YN CHAR(1) NULL COMMENT '노쇼 여부' AFTER ATTENDED_YN,
    ADD UNIQUE KEY UK_HM_MEETING_WAITING_ORDER (MEETING_ID, WAITING_ORDER),
    ADD CONSTRAINT CK_HM_MEETING_PARTICIPANT_STATUS CHECK (PARTICIPATION_STATUS IN ('CONFIRMED','WAITING','OFFERED','CANCELED','ATTENDED','ABSENT')),
    ADD CONSTRAINT CK_HM_MEETING_OFFER_RESPONSE CHECK (OFFER_RESPONSE IS NULL OR OFFER_RESPONSE IN ('ACCEPTED','DECLINED','EXPIRED')),
    ADD CONSTRAINT CK_HM_MEETING_ATTENDED_YN CHECK (ATTENDED_YN IS NULL OR ATTENDED_YN IN ('Y','N')),
    ADD CONSTRAINT CK_HM_MEETING_NO_SHOW_YN CHECK (NO_SHOW_YN IS NULL OR NO_SHOW_YN IN ('Y','N'));

-- 5. 모임 게시판 유형·연결 제약·댓글 1단계
ALTER TABLE HM_CLUB_POST
    DROP CONSTRAINT CK_HM_CLUB_POST_TYPE,
    DROP CONSTRAINT CK_HM_CLUB_POST_STATUS;

UPDATE HM_CLUB_POST SET POST_TYPE = 'MEETING' WHERE POST_TYPE = 'MEETING_RECRUIT';
UPDATE HM_CLUB_POST SET POST_TYPE = 'REVIEW' WHERE POST_TYPE = 'MEETING_REVIEW';

ALTER TABLE HM_CLUB_POST
    ADD COLUMN MEETING_RECRUIT_KEY BIGINT UNSIGNED
        AS (CASE WHEN POST_TYPE = 'MEETING' THEN MEETING_ID ELSE NULL END) PERSISTENT
        COMMENT '만남별 모집글 중복 방지용 생성 컬럼',
    ADD COLUMN REVIEW_AUTHOR_KEY BIGINT UNSIGNED
        AS (CASE WHEN POST_TYPE = 'REVIEW' THEN AUTHOR_MEMBER_ID ELSE NULL END) PERSISTENT
        COMMENT '만남별 회원 후기 중복 방지용 생성 컬럼',
    ADD UNIQUE KEY UK_HM_CLUB_POST_MEETING (MEETING_RECRUIT_KEY),
    ADD UNIQUE KEY UK_HM_CLUB_POST_REVIEW (MEETING_ID, REVIEW_AUTHOR_KEY),
    ADD KEY IX_HM_CLUB_POST_CREATED (CREATED_AT),
    ADD FULLTEXT KEY FX_HM_CLUB_POST_SEARCH (TITLE, CONTENT),
    ADD CONSTRAINT CK_HM_CLUB_POST_TYPE CHECK (POST_TYPE IN ('NOTICE','FREE','MEETING','REVIEW')),
    ADD CONSTRAINT CK_HM_CLUB_POST_STATUS CHECK (POST_STATUS IN ('ACTIVE','CANCELED','DELETED','BLOCKED'));

ALTER TABLE HM_CLUB_COMMENT
