-- 10. 알림 및 알림 설정
CREATE TABLE IF NOT EXISTS HM_NOTIFICATION (
    NOTIFICATION_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '알림 PK',
    MEMBER_ID BIGINT UNSIGNED NOT NULL COMMENT '수신 회원 FK',
    NOTIFICATION_TYPE VARCHAR(50) NOT NULL COMMENT '알림 유형',
    PRIORITY VARCHAR(20) NOT NULL DEFAULT 'NORMAL' COMMENT '중요도: NORMAL, IMPORTANT',
    TITLE VARCHAR(300) NOT NULL COMMENT '알림 제목',
    CONTENT VARCHAR(2000) NOT NULL COMMENT '알림 내용',
    TARGET_TYPE VARCHAR(30) NULL COMMENT '연결 대상 유형',
    TARGET_ID BIGINT UNSIGNED NULL COMMENT '연결 대상 PK',
    READ_STATUS VARCHAR(10) NOT NULL DEFAULT 'UNREAD' COMMENT '읽음 상태: READ, UNREAD',
    READ_AT DATETIME NULL COMMENT '읽음 일시',
    ACTION_TYPE VARCHAR(30) NULL COMMENT '액션 유형: WAITING_OFFER 등',
    ACTION_STATUS VARCHAR(20) NOT NULL DEFAULT 'NONE' COMMENT '액션 상태',
    ACTION_EXPIRES_AT DATETIME NULL COMMENT '액션 만료 일시',
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '생성 일시',
    EXPIRES_AT DATETIME NOT NULL COMMENT '90일 보관 만료 일시',
    PRIMARY KEY (NOTIFICATION_ID),
    KEY IX_HM_NOTIFICATION_MEMBER_READ (MEMBER_ID, READ_STATUS, CREATED_AT),
    KEY IX_HM_NOTIFICATION_EXPIRES (EXPIRES_AT),
    CONSTRAINT FK_HM_NOTIFICATION_MEMBER FOREIGN KEY (MEMBER_ID) REFERENCES HM_MEMBER (MEMBER_ID),
    CONSTRAINT CK_HM_NOTIFICATION_PRIORITY CHECK (PRIORITY IN ('NORMAL','IMPORTANT')),
    CONSTRAINT CK_HM_NOTIFICATION_READ CHECK (READ_STATUS IN ('READ','UNREAD')),
    CONSTRAINT CK_HM_NOTIFICATION_ACTION CHECK (ACTION_STATUS IN ('NONE','PENDING','ACCEPTED','DECLINED','EXPIRED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='회원 알림';

CREATE TABLE IF NOT EXISTS HM_MEMBER_NOTIFICATION_SETTING (
    MEMBER_ID BIGINT UNSIGNED NOT NULL COMMENT '회원 PK/FK',
    COMMENT_YN CHAR(1) NOT NULL DEFAULT 'Y',
    REPLY_YN CHAR(1) NOT NULL DEFAULT 'Y',
    LIKE_YN CHAR(1) NOT NULL DEFAULT 'Y',
    CLUB_NOTICE_YN CHAR(1) NOT NULL DEFAULT 'Y',
    MEETING_YN CHAR(1) NOT NULL DEFAULT 'Y',
    CLUB_ACTIVITY_YN CHAR(1) NOT NULL DEFAULT 'Y',
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (MEMBER_ID),
    CONSTRAINT FK_HM_MEMBER_NOTIFICATION_SETTING_MEMBER FOREIGN KEY (MEMBER_ID) REFERENCES HM_MEMBER (MEMBER_ID),
